-- DISPOSABLE TEST PROJECT ONLY. Contains no production records or user IDs.
-- Deliberately reproduces the observed insecure policies and grants.
-- CREATE TABLE has no IF NOT EXISTS: an existing applications table aborts
-- this transaction rather than being replaced, emptied, or reset.
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';
SET LOCAL transaction_timeout = '60s';
SET LOCAL search_path = pg_catalog;

DO $preflight$
BEGIN
  IF current_setting('server_version_num')::integer / 10000 <> 17 THEN
    RAISE EXCEPTION 'The disposable fixture requires PostgreSQL 17';
  END IF;
END;
$preflight$;

CREATE TABLE public.applications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT timezone('utc'::text, now()),
  company text NOT NULL,
  role text NOT NULL,
  website text,
  logo_url text,
  date_applied date NOT NULL,
  status text NOT NULL DEFAULT 'Applied',
  notes text,
  user_id uuid REFERENCES auth.users(id) ON DELETE CASCADE
);

ALTER TABLE public.applications ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Users can view their own applications"
  ON public.applications FOR SELECT USING (auth.uid() = user_id);
CREATE POLICY "Users can insert their own applications"
  ON public.applications FOR INSERT WITH CHECK (auth.uid() = user_id);
CREATE POLICY "Users can update their own applications"
  ON public.applications FOR UPDATE
  USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
CREATE POLICY "Users can delete their own applications"
  ON public.applications FOR DELETE USING (auth.uid() = user_id);

CREATE POLICY "Enable read access for all users"
  ON public.applications FOR SELECT USING (true);
CREATE POLICY "Enable insert access for all users"
  ON public.applications FOR INSERT WITH CHECK (true);
CREATE POLICY "Enable update access for all users"
  ON public.applications FOR UPDATE USING (true);
CREATE POLICY "Enable delete access for all users"
  ON public.applications FOR DELETE USING (true);

REVOKE ALL PRIVILEGES ON TABLE public.applications FROM PUBLIC;
REVOKE ALL PRIVILEGES ON SEQUENCE public.applications_id_seq FROM PUBLIC;
GRANT ALL PRIVILEGES ON TABLE public.applications TO anon, authenticated;
GRANT ALL PRIVILEGES ON SEQUENCE public.applications_id_seq TO anon, authenticated;
